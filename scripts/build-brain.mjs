// Turns the high-detail brain scan (models/brain-src/Brain_AS.stl, ~3M triangles) into a compact
// mesh for the neural HUD (renderer/brain-mesh.js). Run: node scripts/build-brain.mjs [triangles]
// Model: "Brain AS" by Agnieszka Starostecka, Wikimedia Commons, CC BY 4.0.
import fs from 'fs';
import { MeshoptSimplifier } from 'meshoptimizer';

const TARGET_TRIS = Number(process.argv[2]) || 80000;
const buf = fs.readFileSync(new URL('../models/brain-src/Brain_AS.stl', import.meta.url));
const tris = buf.readUInt32LE(80);
console.log(`source: ${tris.toLocaleString()} triangles`);

// Weld shared corners (STL stores every triangle's corners separately)
const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
for (let t = 0; t < tris; t++) for (let v = 0; v < 3; v++) for (let k = 0; k < 3; k++) {
  const x = buf.readFloatLE(84 + t * 50 + 12 + v * 12 + k * 4);
  if (x < lo[k]) lo[k] = x;
  if (x > hi[k]) hi[k] = x;
}
const q = Math.hypot(hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]) * 1e-6;
const map = new Map();
const pos = [];
const idx = new Uint32Array(tris * 3);
for (let t = 0; t < tris; t++) for (let v = 0; v < 3; v++) {
  const o = 84 + t * 50 + 12 + v * 12;
  const x = buf.readFloatLE(o), y = buf.readFloatLE(o + 4), z = buf.readFloatLE(o + 8);
  const key = `${Math.round(x / q)},${Math.round(y / q)},${Math.round(z / q)}`;
  let i = map.get(key);
  if (i === undefined) { i = pos.length / 3; map.set(key, i); pos.push(x, y, z); }
  idx[t * 3 + v] = i;
}
console.log(`welded: ${(pos.length / 3).toLocaleString()} vertices`);

await MeshoptSimplifier.ready;
const positions = new Float32Array(pos);
const [simple, err] = MeshoptSimplifier.simplify(idx, positions, 3, TARGET_TRIS * 3, 0.02, ['Prune']);
console.log(`simplified: ${(simple.length / 3).toLocaleString()} triangles (error ${err.toFixed(4)})`);

// Keep only used vertices; centre and scale into [-1, 1]
const remap = new Map();
const outPos = [];
const outIdx = new Uint32Array(simple.length);
for (let i = 0; i < simple.length; i++) {
  let j = remap.get(simple[i]);
  if (j === undefined) { j = outPos.length / 3; remap.set(simple[i], j); outPos.push(...positions.subarray(simple[i] * 3, simple[i] * 3 + 3)); }
  outIdx[i] = j;
}
const c = [0, 1, 2].map((k) => (lo[k] + hi[k]) / 2);
const half = Math.max(...[0, 1, 2].map((k) => (hi[k] - lo[k]) / 2));
console.log('extent (x, y, z):', [0, 1, 2].map((k) => ((hi[k] - lo[k]) / 2 / half).toFixed(2)).join(', '));
const q16 = new Int16Array(outPos.length);
for (let i = 0; i < outPos.length; i++) q16[i] = Math.round(((outPos[i] - c[i % 3]) / half) * 32767);
const vertCount = outPos.length / 3;
const indexArr = vertCount < 65536 ? Uint16Array.from(outIdx) : outIdx;

const b64 = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
fs.writeFileSync(new URL('../src/renderer/brain-mesh.js', import.meta.url),
  `// Generated by scripts/build-brain.mjs from "Brain AS" by Agnieszka Starostecka (Wikimedia Commons, CC BY 4.0).\n` +
  `// Positions: Int16, scaled to [-1, 1]. Indices: ${indexArr.BYTES_PER_ELEMENT === 2 ? 'Uint16' : 'Uint32'}.\n` +
  `export const vertexCount = ${vertCount};\nexport const indexBits = ${indexArr.BYTES_PER_ELEMENT * 8};\n` +
  `export const positions = '${b64(q16)}';\nexport const indices = '${b64(indexArr)}';\n`);
console.log(`wrote src/renderer/brain-mesh.js: ${vertCount.toLocaleString()} vertices, ${(fs.statSync(new URL('../src/renderer/brain-mesh.js', import.meta.url)).size / 1024).toFixed(0)} KB`);
